function shuffleArray<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function getSimceBankForGrade(grade: SimceGradeLevel): SimceBankQuestion[] {
  return SIMCE_QUESTION_BANK.filter(q => q.grade === grade);
}

/**
 * Construye una evaluación tipo SIMCE equilibrada para 4°, 6° u 8° básico,
 * distribuyendo preguntas entre ejes cuando se elige Ensayo Integral ('all')
 * o enfocándose estrictamente en un eje específico sin repetir ítems.
 */
export function buildSimceExamQuestions(params: {
  grade: SimceGradeLevel;
  axisFilter: ThematicAxis | 'all';
  difficulty: DifficultyLevel;
  count: number;
}): SimceBankQuestion[] {
  const { grade, axisFilter, difficulty, count } = params;
  const gradeBank = getSimceBankForGrade(grade);

  const pool =
    axisFilter === 'all'
      ? gradeBank
      : gradeBank.filter(q => q.axis === axisFilter);

  const safeCount = Math.min(count, pool.length);

  // Order or filter according to difficulty preference
  let orderedCandidates: SimceBankQuestion[] = [];
  if (difficulty === 'progresivo') {
    const faciles = shuffleArray(pool.filter(q => q.difficulty === 'facil'));
    const medios = shuffleArray(pool.filter(q => q.difficulty === 'medio'));
    const dificiles = shuffleArray(pool.filter(q => q.difficulty === 'dificil'));
    orderedCandidates = [...faciles, ...medios, ...dificiles];
  } else {
    const primary = shuffleArray(pool.filter(q => q.difficulty === difficulty));
    const secondary = shuffleArray(pool.filter(q => q.difficulty !== difficulty));
    orderedCandidates = [...primary, ...secondary];
  }

  // If Ensayo Integral ('all'), pick in round-robin across axes first so every axis is represented!
  if (axisFilter === 'all') {
    const axesOrder: ThematicAxis[] = [
      'numeros_operaciones',
      'patrones_algebra',
      'geometria',
      'medicion',
      'datos_probabilidades',
    ];
    const buckets: Record<ThematicAxis, SimceBankQuestion[]> = {
      numeros_operaciones: [],
      patrones_algebra: [],
      geometria: [],
      medicion: [],
      datos_probabilidades: [],
    };

    orderedCandidates.forEach(q => {
      buckets[q.axis].push(q);
    });

    const selected: SimceBankQuestion[] = [];
    let added = true;
    while (selected.length < safeCount && added) {
      added = false;
      for (const ax of axesOrder) {
        if (selected.length >= safeCount) break;
        const nextItem = buckets[ax].shift();
        if (nextItem) {
          selected.push(nextItem);
          added = true;
        }
      }
    }

    // Re-sort progressively if difficulty === 'progresivo'
    if (difficulty === 'progresivo') {
      const weight = { facil: 1, medio: 2, dificil: 3, progresivo: 2 };
      return selected.sort((a, b) => weight[a.difficulty] - weight[b.difficulty]);
    }
    return selected;
  }

  return orderedCandidates.slice(0, safeCount);
}

/**
 * Reemplaza una pregunta específica dentro de un ensayo SIMCE por otra real del mismo banco
 * sin duplicar las ya seleccionadas.
 */
export function pickReplacementSimceQuestion(params: {
  grade: SimceGradeLevel;
  axisFilter: ThematicAxis | 'all';
  existingIds: string[];
  preferredAxis?: ThematicAxis;
}): SimceBankQuestion | null {
  const { grade, axisFilter, existingIds, preferredAxis } = params;
  const usedSet = new Set(existingIds);
  const gradeBank = getSimceBankForGrade(grade);

  const candidatesSameAxis = gradeBank.filter(
    q => !usedSet.has(q.id) && (preferredAxis ? q.axis === preferredAxis : true)
  );
  if (candidatesSameAxis.length > 0) {
    return candidatesSameAxis[Math.floor(Math.random() * candidatesSameAxis.length)];
  }

  const fallbackCandidates = gradeBank.filter(
    q => !usedSet.has(q.id) && (axisFilter === 'all' || q.axis === axisFilter)
  );
  if (fallbackCandidates.length > 0) {
    return fallbackCandidates[Math.floor(Math.random() * fallbackCandidates.length)];
  }

  return null;
}
