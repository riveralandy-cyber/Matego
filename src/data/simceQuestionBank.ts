function shuffleArray<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

const GRADE_BANK_CACHE: Partial<Record<SimceGradeLevel, SimceBankQuestion[]>> = {};

export function getSimceBankForGrade(grade: SimceGradeLevel): SimceBankQuestion[] {
  const cached = GRADE_BANK_CACHE[grade];
  if (cached) return cached;

  const curated = SIMCE_QUESTION_BANK.filter(q => q.grade === grade);
  const countByAxis: Record<ThematicAxis, number> = {
    numeros_operaciones: 0,
    patrones_algebra: 0,
    geometria: 0,
    medicion: 0,
    datos_probabilidades: 0,
  };
  curated.forEach(q => {
    countByAxis[q.axis] = (countByAxis[q.axis] || 0) + 1;
  });

  const seededExtras = generateSeededParametricSimceForGrade(grade, countByAxis, 50);
  const combined = [...curated, ...seededExtras];
  GRADE_BANK_CACHE[grade] = combined;
  return combined;
}

/**
 * Construye una evaluación tipo SIMCE equilibrada para 4°, 6° u 8° básico,
 * combinando preguntas oficiales liberadas del banco curado con variaciones
 * paramétricas frescas (números, contextos, tablas y gráficos nuevos en cada ensayo).
 */
export function buildSimceExamQuestions(params: {
  grade: SimceGradeLevel;
  axisFilter: ThematicAxis | 'all';
  difficulty: DifficultyLevel;
  count: number;
  excludePrompts?: Set<string> | string[];
}): SimceBankQuestion[] {
  const { grade, axisFilter, difficulty, count, excludePrompts } = params;
  const excludedSet = new Set<string>(excludePrompts ? Array.from(excludePrompts) : []);

  const curatedPool = SIMCE_QUESTION_BANK.filter(
    q => q.grade === grade && (axisFilter === 'all' || q.axis === axisFilter)
  );
  const rounds = axisFilter === 'all' ? 3 : Math.max(5, Math.ceil(count / 4));
  const freshPool = generateFreshParametricSimceBatch({
    grade,
    axisFilter,
    roundsPerTemplate: rounds,
  });

  // Merge fresh dynamic variations + curated official bank, deduplicating prompts
  const mergedMap = new Map<string, SimceBankQuestion>();
  for (const q of shuffleArray([...freshPool, ...curatedPool])) {
    const pKey = q.prompt.trim();
    if (!mergedMap.has(pKey)) {
      mergedMap.set(pKey, q);
    }
  }
  let pool = Array.from(mergedMap.values());

  // Fallback to seeded grade bank if count still exceeds pool
  if (pool.length < count) {
    const seededPool = getSimceBankForGrade(grade).filter(
      q => axisFilter === 'all' || q.axis === axisFilter
    );
    for (const q of shuffleArray(seededPool)) {
      const pKey = q.prompt.trim();
      if (!mergedMap.has(pKey)) {
        mergedMap.set(pKey, q);
      }
    }
    pool = Array.from(mergedMap.values());
  }

  const safeCount = Math.min(count, pool.length);

  const orderByDifficulty = (subset: SimceBankQuestion[]): SimceBankQuestion[] => {
    if (difficulty === 'progresivo') {
      const faciles = shuffleArray(subset.filter(q => q.difficulty === 'facil'));
      const medios = shuffleArray(subset.filter(q => q.difficulty === 'medio'));
      const dificiles = shuffleArray(subset.filter(q => q.difficulty === 'dificil'));
      return [...faciles, ...medios, ...dificiles];
    }
    const primary = shuffleArray(subset.filter(q => q.difficulty === difficulty));
    const secondary = shuffleArray(subset.filter(q => q.difficulty !== difficulty));
    return [...primary, ...secondary];
  };

  // Prioritize items not seen in recent practice rounds
  const unseenPool = pool.filter(q => !excludedSet.has(q.prompt.trim()));
  const seenPool = pool.filter(q => excludedSet.has(q.prompt.trim()));
  const orderedCandidates = [...orderByDifficulty(unseenPool), ...orderByDifficulty(seenPool)];

  // If Ensayo Integral ('all'), pick in round-robin across axes first so every axis is represented!
  if (axisFilter === 'all') {
    const axesOrder: ThematicAxis[] = [
      'numeros_operaciones',
      'patrones_algebra',
      'geometria',
      'medicion',
      'datos_probabilidades',
    ];
    const buckets: Record<ThematicAxis, SimceBankQuestion[]> = {
      numeros_operaciones: [],
      patrones_algebra: [],
      geometria: [],
      medicion: [],
      datos_probabilidades: [],
    };

    orderedCandidates.forEach(q => {
      buckets[q.axis].push(q);
    });

    const selected: SimceBankQuestion[] = [];
    let added = true;
    while (selected.length < safeCount && added) {
      added = false;
      for (const ax of axesOrder) {
        if (selected.length >= safeCount) break;
        const nextItem = buckets[ax].shift();
        if (nextItem) {
          selected.push(nextItem);
          added = true;
        }
      }
    }

    // Re-sort progressively if difficulty === 'progresivo'
    if (difficulty === 'progresivo') {
      const weight = { facil: 1, medio: 2, dificil: 3, progresivo: 2 };
      return selected.sort((a, b) => weight[a.difficulty] - weight[b.difficulty]);
    }
    return selected;
  }

  return orderedCandidates.slice(0, safeCount);
}

/**
 * Reemplaza una pregunta específica dentro de un ensayo SIMCE por otra del mismo eje
 * (combinando ítems curados y variaciones paramétricas recién generadas) sin duplicar.
 */
export function pickReplacementSimceQuestion(params: {
  grade: SimceGradeLevel;
  axisFilter: ThematicAxis | 'all';
  existingIds: string[];
  preferredAxis?: ThematicAxis;
}): SimceBankQuestion | null {
  const { grade, axisFilter, existingIds, preferredAxis } = params;
  const usedSet = new Set(existingIds);
  const targetAxis: ThematicAxis =
    preferredAxis || (axisFilter === 'all' ? 'numeros_operaciones' : axisFilter);

  // 65% chance to serve a brand-new live parametric variation so swaps feel inexhaustible
  if (Math.random() < 0.65) {
    const fresh = generateSingleFreshSimceItem({ grade, axis: targetAxis });
    if (fresh && !usedSet.has(fresh.id)) {
      return fresh;
    }
  }

  const gradeBank = getSimceBankForGrade(grade);
  const candidatesSameAxis = gradeBank.filter(
    q => !usedSet.has(q.id) && (preferredAxis ? q.axis === preferredAxis : true)
  );
  if (candidatesSameAxis.length > 0) {
    return candidatesSameAxis[Math.floor(Math.random() * candidatesSameAxis.length)];
  }

  const freshFallback = generateSingleFreshSimceItem({ grade, axis: targetAxis });
  if (freshFallback) return freshFallback;

  const fallbackCandidates = gradeBank.filter(
    q => !usedSet.has(q.id) && (axisFilter === 'all' || q.axis === axisFilter)
  );
  if (fallbackCandidates.length > 0) {
    return fallbackCandidates[Math.floor(Math.random() * fallbackCandidates.length)];
  }

  return null;
}
